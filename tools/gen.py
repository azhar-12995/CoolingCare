"""Generates app resources from the design sources. Run from anywhere:  python tools/gen.py

- fonts   tools/fonts/*.ttf           -> composeResources/font (Inter subset to Latin)
- images  tools/images/out/*.png      -> composeResources/drawable/img_*.webp
- icons   tools/figma/icons.json      -> ui/icons/CcIcons.kt  (Lucide ISC + custom WhatsApp glyph)
- catalog tools/catalog.json          -> data/Catalog.kt     (services, slots, areas, FAQs, business info)
"""
import json, os, re, shutil
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'composeApp/src/commonMain/composeResources')
KT = os.path.join(ROOT, 'composeApp/src/commonMain/kotlin/com/coolingcare/app')
T = os.path.join(ROOT, 'tools')


def fonts():
    out = os.path.join(RES, 'font'); os.makedirs(out, exist_ok=True)
    for f in ['poppins_regular', 'poppins_medium', 'poppins_semibold', 'poppins_bold', 'nastaliq_regular', 'nastaliq_semibold', 'nastaliq_bold']:
        shutil.copy(os.path.join(T, 'fonts', f + '.ttf'), os.path.join(out, f + '.ttf'))
    from fontTools import subset
    for w in ['regular', 'medium', 'semibold', 'bold']:
        opts = subset.Options(); opts.layout_features = ['*']; opts.name_IDs = ['*']
        font = subset.load_font(os.path.join(T, 'fonts', f'inter_{w}.ttf'), opts)
        s = subset.Subsetter(opts)
        s.populate(unicodes=list(range(0x20, 0x250)) + list(range(0x2000, 0x2070)) + list(range(0x20A0, 0x20C0)) + list(range(0x2190, 0x2200)) + [0x2605, 0x2606, 0x2713, 0x2122, 0x2116])
        s.subset(font); subset.save_font(font, os.path.join(out, f'inter_{w}.ttf'), opts)
    print('fonts ok')


MAXW = {'welcome_scene': 1200, 'detail_deep_clean': 1180, 'big_fridge': 640, 'hero_technician': 520}


def images():
    out = os.path.join(RES, 'drawable'); os.makedirs(out, exist_ok=True)
    src = os.path.join(T, 'images/out')
    for f in sorted(os.listdir(src)):
        if not f.endswith('.png'): continue
        k = f[:-4]; im = Image.open(os.path.join(src, f))
        mw = MAXW.get(k, 1000)
        if im.width > mw: im = im.resize((mw, round(im.height * mw / im.width)), Image.LANCZOS)
        im.save(os.path.join(out, f'img_{k}.webp'), 'WEBP', quality=88, method=6)
    print('images ok')


def svg_to_paths(svg):
    """-> list of (d, filled)"""
    out = []
    for tag, attrs in re.findall(r'<(\w+) ([^>]*?)/>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
        filled = a.get('fill') not in (None, 'none') and a.get('stroke') == 'none'
        f = lambda k, d=0.0: float(a.get(k, d))
        if tag == 'path': d = a['d']
        elif tag == 'line': d = f"M{f('x1')} {f('y1')}L{f('x2')} {f('y2')}"
        elif tag in ('circle', 'ellipse'):
            cx, cy = f('cx'), f('cy'); rx = f('r') if tag == 'circle' else f('rx'); ry = f('r') if tag == 'circle' else f('ry')
            d = f"M{cx - rx} {cy}a{rx} {ry} 0 1 0 {2 * rx} 0a{rx} {ry} 0 1 0 {-2 * rx} 0"
        elif tag == 'rect':
            x, y, w, h = f('x'), f('y'), f('width'), f('height'); rx = f('rx', 0); ry = f('ry', rx)
            if rx == 0: d = f"M{x} {y}h{w}v{h}h{-w}z"
            else: d = (f"M{x + rx} {y}h{w - 2 * rx}a{rx} {ry} 0 0 1 {rx} {ry}v{h - 2 * ry}a{rx} {ry} 0 0 1 {-rx} {ry}"
                       f"h{-(w - 2 * rx)}a{rx} {ry} 0 0 1 {-rx} {-ry}v{-(h - 2 * ry)}a{rx} {ry} 0 0 1 {rx} {-ry}z")
        elif tag in ('polyline', 'polygon'):
            pts = re.findall(r'-?[\d.]+', a['points']); pairs = [f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts), 2)]
            d = 'M' + 'L'.join(pairs) + ('z' if tag == 'polygon' else '')
        else: continue
        out.append((d, filled))
    return out


def icons():
    data = json.load(open(os.path.join(T, 'figma/icons.json'), encoding='utf8'))
    camel = lambda n: ''.join(p.capitalize() for p in n.split('-'))
    lines = ['// GENERATED by tools/gen.py from tools/figma/icons.json — Lucide icons (ISC licence) + custom WhatsApp glyph. Do not edit.',
             'package com.coolingcare.app.ui.icons', '',
             'import androidx.compose.ui.graphics.vector.ImageVector', '',
             'object CcIcons {']
    for n in sorted(data):
        ps = svg_to_paths(data[n])
        args = ', '.join(('F' if fl else 'S') + '("' + d + '")' for d, fl in ps)
        lines.append(f'    val {camel(n)}: ImageVector by lazy {{ icon("{n}", {args}) }}')
    lines.append('}')
    os.makedirs(os.path.join(KT, 'ui/icons'), exist_ok=True)
    open(os.path.join(KT, 'ui/icons/CcIcons.kt'), 'w', encoding='utf8').write('\n'.join(lines) + '\n')
    print('icons ok', len(data))


def kstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'
def tx(o): return f"Txt({kstr(o['en'])}, {kstr(o['ur'])})"


def catalog():
    c = json.load(open(os.path.join(T, 'catalog.json'), encoding='utf8'))
    b = c['business']
    L = ['// GENERATED by tools/gen.py from tools/catalog.json — edit the JSON (business info, services, slots, areas, FAQs) and re-run.',
         'package com.coolingcare.app.data', '',
         'import com.coolingcare.app.res.Res', 'import com.coolingcare.app.res.*', 'import com.coolingcare.app.model.*', '',
         'object Catalog {',
         f"    val business = Business(name = {kstr(b['name'])}, tagline = {tx(b['tagline'])}, city = {tx(b['city'])}, phoneDisplay = {kstr(b['phoneDisplay'])},",
         f"        phoneDial = {kstr(b['phoneDial'])}, whatsapp = {kstr(b['whatsapp'])}, hours = {tx(b['hours'])}, hoursNote = {tx(b['hoursNote'])})", '',
         '    val categories = listOf(' + ', '.join(f"Category({kstr(x['id'])}, Txt({kstr(x['en'])}, {kstr(x['ur'])}))" for x in c['categories']) + ')', '',
         '    val appliances = listOf(']
    for a in c['appliances']:
        L.append(f"        Appliance({kstr(a['id'])}, Txt({kstr(a['en'])}, {kstr(a['ur'])}), Res.drawable.img_{a['img']}, {kstr(a['category'])}),")
    L.append('    )'); L.append('')
    L.append('    /** Offline default for the service list (the live list comes from Firestore services/, seeded from the same JSON). */')
    L.append('    val services = listOf(')
    for i, s in enumerate(c['services']):
        inc = ', '.join(tx(x) for x in s['included'])
        lt = tx(s['listTitle']) if 'listTitle' in s else tx(s['title'])
        L.append(f"        Service(id = {kstr(s['id'])}, category = {kstr(s['category'])}, sort = {(i + 1) * 10}, image = {kstr(s['img'])}, header = {kstr(s['header'])},")
        L.append(f"            title = {tx(s['title'])}, listTitle = {lt}, short = {tx(s['short'])},")
        L.append(f"            about = {tx(s['about'])}, included = listOf({inc}), duration = {tx(s['duration'])}),")
    L.append('    )'); L.append('')
    # every product / service picture an admin can pick for a service
    keys = sorted(f[4:-5] for f in os.listdir(os.path.join(RES, 'drawable')) if f.startswith('img_') and f.endswith('.webp')
                  and f[4:-5] not in ('hero_technician', 'tech_portrait', 'welcome_scene'))
    L.append('    /** Bundled pictures by key (services store the key). */')
    L.append('    val images = mapOf(' + ', '.join(f'{kstr(k)} to Res.drawable.img_{k}' for k in keys) + ')')
    L.append('    /** Product shots on a light background: shown whole (Fit) instead of cropped. */')
    L.append('    val fitImages = setOf(' + ', '.join(kstr(k) for k in keys if k.startswith('cat_') or k == 'big_fridge') + ')')
    L.append('')
    L.append('    val timeSlots = listOf(' + ', '.join(f"TimeSlot({kstr(t['id'])}, {int(t['id'].split('-')[0])}, {int(t['id'].split('-')[1])}, Txt({kstr(t['en'])}, {kstr(t['ur'])}))" for t in c['timeSlots']) + ')')
    L.append('    val areas = listOf(' + ', '.join(tx(a) for a in c['areas']) + ')')
    L.append('    val faqs = listOf(')
    for f in c['faqs']: L.append(f"        Faq({tx(f['q'])}, {tx(f['a'])}),")
    L.append('    )'); L.append('')
    L.append('    fun appliance(id: String) = appliances.firstOrNull { it.id == id }')
    L.append('    fun slot(id: String) = timeSlots.firstOrNull { it.id == id }')
    L.append('}')
    os.makedirs(os.path.join(KT, 'data'), exist_ok=True)
    open(os.path.join(KT, 'data/Catalog.kt'), 'w', encoding='utf8').write('\n'.join(L) + '\n')
    print('catalog ok', len(c['services']), 'services')




def android_res():
    """Launcher icon (adaptive + monochrome), notification icon and Android 12 splash icon from the Lucide snowflake."""
    import importlib
    data = json.load(open(os.path.join(T, 'figma/icons.json'), encoding='utf8'))
    paths = [d for d, _ in svg_to_paths(data['snowflake'])]
    res = os.path.join(ROOT, 'composeApp/src/androidMain/res')
    def strokes(color, width):
        return ''.join(f'\n        <path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>' for d in paths)
    def vec(name, w, vp, body):
        os.makedirs(os.path.join(res, 'drawable'), exist_ok=True)
        open(os.path.join(res, 'drawable', name + '.xml'), 'w', encoding='utf8').write(
            f'<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{w}dp" android:height="{w}dp" android:viewportWidth="{vp}" android:viewportHeight="{vp}">{body}\n</vector>\n')
    # notification: 24dp white
    vec('ic_stat_snowflake', 24, 24, strokes('#FFFFFFFF', 2))
    # adaptive foreground: snowflake 52.8dp in the 72dp safe zone of a 108dp canvas
    vec('ic_launcher_foreground', 108, 108, f'\n    <group android:scaleX="2.2" android:scaleY="2.2" android:translateX="27.6" android:translateY="27.6">{strokes("#FFFFFFFF", 1.7)}\n    </group>')
    vec('ic_launcher_monochrome', 108, 108, f'\n    <group android:scaleX="2.2" android:scaleY="2.2" android:translateX="27.6" android:translateY="27.6">{strokes("#FF000000", 1.7)}\n    </group>')
    vec('ic_launcher_background', 108, 108, '\n    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108"\n                android:startColor="#FF0A66C8" android:endColor="#FF0B3D91"/>\n        </aapt:attr>\n    </path>')
    # Android 12+ splash icon: white snowflake on the brand-blue splash (system masks it to a circle)
    vec('ic_splash', 108, 108, f'\n    <group android:scaleX="2.0" android:scaleY="2.0" android:translateX="30" android:translateY="30">{strokes("#FFFFFFFF", 1.7)}\n    </group>')
    os.makedirs(os.path.join(res, 'mipmap-anydpi-v26'), exist_ok=True)
    for n in ['ic_launcher', 'ic_launcher_round']:
        open(os.path.join(res, 'mipmap-anydpi-v26', n + '.xml'), 'w', encoding='utf8').write(
            '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n')
    print('android res ok')


if __name__ == '__main__':
    fonts(); images(); icons(); catalog(); android_res()
